import type { LevelDef, PathDef } from "./types";

function path(cells: [number, number][]): PathDef {
  return { cells: cells.map(([row, col]) => ({ row, col })) };
}

function level(rows: number, cols: number, paths: PathDef[]): LevelDef {
  return { rows, cols, paths };
}

